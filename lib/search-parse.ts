/**
 * Единая нормализация пользовательского запроса для поиска.
 * Приводит все формы записи размеров к одному виду:
 * «60x40x3», «60 х 40 х 3», «60×40×3», «60*40*3», «60,5x4» → «60x40x3» / «60.5x4».
 *
 * Правила:
 * - разделители размеров х (кириллица) / x / X / × / * → латинская «x»
 * - десятичная запятая → точка
 * - пробелы вокруг разделителя размеров убираются («60 x 40» → «60x40»)
 * - множественные пробелы схлопываются, регистр приводится к нижнему
 */
export function normalizeQuery(raw: string): string {
  return raw
    .trim()
    .toLowerCase()
    .replace(/[х×*]/gi, 'x') // все варианты разделителя → латинская x
    .replace(/(\d),(\d)/g, '$1.$2') // десятичная запятая между цифрами → точка
    .replace(/(\d)\s*x\s*(\d)/g, '$1x$2') // «60 x 40» → «60x40»
    .replace(/(\d)\s*x\s*(\d)/g, '$1x$2') // повтор для цепочек «60x40 x 3»
    .replace(/\s+/g, ' ')
}
